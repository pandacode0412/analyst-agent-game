CREATE TABLE observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id TEXT NOT NULL,
    observed_at_utc TIMESTAMPTZ NOT NULL,
    red_markers INTEGER NOT NULL CHECK (red_markers >= 0),
    blue_markers INTEGER NOT NULL CHECK (blue_markers >= 0),
    status TEXT NOT NULL CHECK (status = 'OBSERVED_NOT_CONFIRMED'),
    evidence_path TEXT
);

CREATE INDEX idx_observations_time_table ON observations (observed_at_utc, table_id);

CREATE TABLE confirmed_rounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id TEXT NOT NULL,
    round_id TEXT NOT NULL,
    finished_at_utc TIMESTAMPTZ NOT NULL,
    result TEXT NOT NULL CHECK (result IN ('BANKER', 'PLAYER', 'TIE')),
    method TEXT NOT NULL CHECK (method IN ('MANUAL_VERIFIED', 'TRUSTED_ROUND_ID')),
    source TEXT NOT NULL,
    reviewer TEXT NOT NULL,
    recorded_at_utc TIMESTAMPTZ NOT NULL,
    UNIQUE (table_id, round_id)
);

CREATE INDEX idx_rounds_finished ON confirmed_rounds (finished_at_utc, table_id);

CREATE TABLE observation_gaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id TEXT NOT NULL,
    detected_at_utc TIMESTAMPTZ NOT NULL,
    reason TEXT NOT NULL
);

CREATE INDEX idx_gaps_time_table ON observation_gaps (detected_at_utc, table_id);
